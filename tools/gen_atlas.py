#!/usr/bin/env python3
"""Генератор атласа глифов для tb-renderer (через tools/raster.so над freetype).

Пишет src/atlas.rs со статичными 8-битными альфа-битмапами.
Запуск: clang -shared -fPIC -O2 -I/usr/include/freetype2 tools/raster.c -o tools/raster.so -lfreetype
        python3 tools/gen_atlas.py
"""
import ctypes
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEXT_CHARS = "escF0123456789"
TEXT_PX = 30
# fa-иконки из Nerd-диапазона (unicode ⏸⏮⏭ = tofu в JetBrains Mono)
SYM_CHARS = "\uf04a\uf04b\uf04c\uf04e\uf185\uf186\uf027\uf028\uf11c\uf068\uf067"  # backward play pause forward sun solid sun-o vol-down vol-up kbd minus plus
SYM2_CHARS = "\uf186\uf185"  # мелкие солнца (контур/залитое) для подсветки клавиатуры
SYM2_PX = 20
SYM_PX = 36

FONT_PREFS = [
    "JetBrainsMonoNerdFontMono-Regular.ttf",
    "JetBrainsMonoNerdFont-Regular.ttf",
    "DejaVuSans.ttf",
]


def find_font():
    out = subprocess.run(["fc-list", ":file"], capture_output=True, text=True).stdout
    files = [line.split(":")[0].strip() for line in out.splitlines()]
    for pref in FONT_PREFS:
        rx = re.compile(re.escape(pref).replace(r"\-", "-"))
        for f in files:
            if rx.search(Path(f).name):
                return f
    return None


def main():
    so = ctypes.CDLL(str(HERE / "raster.so"))
    so.tb_open.argtypes = [ctypes.c_char_p, ctypes.c_int]
    so.tb_open.restype = ctypes.c_int
    so.tb_render.argtypes = [
        ctypes.c_ulong,
        ctypes.POINTER(ctypes.c_uint), ctypes.POINTER(ctypes.c_uint),
        ctypes.POINTER(ctypes.c_int), ctypes.POINTER(ctypes.c_int),
        ctypes.POINTER(ctypes.c_int),
        ctypes.c_char_p, ctypes.c_int,
    ]
    so.tb_render.restype = ctypes.c_int

    path = find_font()
    if not path:
        sys.exit("no font")
    print(f"font: {path}")

    def render(ch, px):
        rc = so.tb_open(path.encode(), px)
        if rc:
            sys.exit(f"tb_open rc={rc}")
        w, h, l, t, a = ctypes.c_uint(), ctypes.c_uint(), ctypes.c_int(), ctypes.c_int(), ctypes.c_int()
        buf = ctypes.create_string_buffer(128 * 128)
        rc = so.tb_render(ord(ch), ctypes.byref(w), ctypes.byref(h), ctypes.byref(l),
                          ctypes.byref(t), ctypes.byref(a), buf, len(buf))
        if rc:
            return None
        rows = [buf.raw[r * w.value:(r + 1) * w.value] for r in range(h.value)]
        return {"w": w.value, "h": h.value, "left": l.value, "top": t.value,
                "advance": a.value, "rows": rows}

    glyphs = []
    for ch in TEXT_CHARS:
        g = render(ch, TEXT_PX)
        if g:
            glyphs.append((ch, "text", g))
        else:
            print(f"MISS text: {ch!r}")
    for ch in SYM2_CHARS:
        g = render(ch, SYM2_PX)
        if g:
            glyphs.append((ch, "sym2", g))
        else:
            print(f"MISS sym2: {ch!r}")
    for ch in SYM_CHARS:
        g = render(ch, SYM_PX)
        if g:
            glyphs.append((ch, "sym", g))
        else:
            print(f"MISS sym: {ch!r}")

    out = ["// AUTOGENERATED by tools/gen_atlas.py — не редактировать руками.",
           "//! 8-битные альфа-битмапы (0..255), отрендерены freetype из системного шрифта.",
           "",
           "pub struct Glyph {",
           "    pub ch: char,",
           "    pub w: u32,",
           "    pub h: u32,",
           "    pub left: i32,",
           "    pub top: i32,",
           "    pub advance: u32,",
           "    pub alpha: &'static [u8],",
           "}",
           "",
           "pub static TEXT: &[&Glyph] = &["]
    out += [f"    &glyph_text_{ord(ch)}," for ch, k, _ in glyphs if k == "text"]
    out.append("];")
    out.append("")
    out.append("pub static SYM: &[&Glyph] = &[")
    out += [f"    &sym_{ord(ch):x}," for ch, k, _ in glyphs if k == "sym"]
    out.append("];")
    out.append("")
    out.append("pub static SYM2: &[&Glyph] = &[")
    out += [f"    &sym2_{ord(ch):x}," for ch, k, _ in glyphs if k == "sym2"]
    out.append("];")
    out.append("")

    def rust_char(ch):
        cp = ord(ch)
        if 0x20 <= cp < 0x7F and ch not in "\\'":
            return "'" + ch + "'"
        return "'\\u{%x}'" % cp

    def emit(ident, ch, g):
        out.append(f"static {ident}: Glyph = Glyph {{ ch: {rust_char(ch)}, w: {g['w']}, h: {g['h']}, left: {g['left']}, top: {g['top']}, advance: {g['advance']}, alpha: &[")
        for row in g["rows"]:
            out.append("    " + ",".join(str(b) for b in row) + ",")
        out.append("] };")

    for ch, k, g in glyphs:
        ident = {"text": f"glyph_text_{ord(ch)}", "sym": f"sym_{ord(ch):x}", "sym2": f"sym2_{ord(ch):x}"}[k]
        emit(ident, ch, g)

    dst = HERE.parent / "src" / "atlas.rs"
    dst.write_text("\n".join(out) + "\n")
    print(f"wrote {dst} ({len(glyphs)} glyphs)")


if __name__ == "__main__":
    main()
